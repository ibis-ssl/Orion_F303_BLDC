/* BLDCブートローダーのFlash/RAM配置と起動条件を一元管理する。 */
#pragma once

#include <stdint.h>

#define BOOTLOADER_FLASH_BASE UINT32_C(0x08000000)
#define BOOTLOADER_FLASH_SIZE UINT32_C(0x00004000)
#define BOOT_APP_BASE UINT32_C(0x08004000)
#define BOOT_APP_SIZE UINT32_C(0x0001B000)
#define BOOT_METADATA_BASE UINT32_C(0x08003800)
#define BOOT_METADATA_SIZE UINT32_C(0x00000800)
#define BOOT_SETTINGS_BASE UINT32_C(0x0801F000)
#define BOOT_SETTINGS_SIZE UINT32_C(0x00001000)

#define BOOT_SRAM_BASE UINT32_C(0x20000000)
#define BOOT_SRAM_END UINT32_C(0x20008000)
#define BOOT_CCMRAM_BASE UINT32_C(0x10000000)
#define BOOT_CCMRAM_END UINT32_C(0x10002000)

#define BOOT_IMAGE_METADATA_MAGIC UINT32_C(0x3157464F)
#define BOOT_IMAGE_METADATA_FORMAT UINT16_C(1)
#define BOOT_APP_SLOT UINT32_C(0)

typedef enum {
  BOOT_IMAGE_STATE_EMPTY = 0,
  BOOT_IMAGE_STATE_RECEIVING = 1,
  BOOT_IMAGE_STATE_VERIFIED = 2,
  BOOT_IMAGE_STATE_PENDING = 3,
  BOOT_IMAGE_STATE_CONFIRMED = 4,
  BOOT_IMAGE_STATE_INVALID = 5,
} boot_image_state_t;
